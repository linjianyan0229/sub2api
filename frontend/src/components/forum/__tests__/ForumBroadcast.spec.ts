import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { flushPromises, mount } from '@vue/test-utils'
import ForumBroadcast from '../ForumBroadcast.vue'

const { events, arrive } = vi.hoisted(() => ({ events: vi.fn(), arrive: vi.fn() }))
vi.mock('@/api/forum', () => ({ forumAPI: { events, arrive } }))
vi.mock('../ForumCelebration.vue', () => ({ __esModule: true, default: { props: ['arrival'], emits: ['close'], template: '<button data-broadcast @click="$emit(\'close\')">{{ arrival.author.username }}</button>' } }))
const arrival = (id: number, age = 0) => ({ id, author: { user_id: 7, username: '星河', avatar_url: '', actual_cost: 123 }, rank: 1, created_at: new Date(Date.now() - age).toISOString() })
beforeEach(() => {
  vi.useFakeTimers()
  events.mockReset(); arrive.mockReset(); arrive.mockResolvedValue(undefined)
  events.mockResolvedValue({ cursor: 10, arrivals: [] })
  Object.defineProperty(document, 'hidden', { configurable: true, value: false })
})
afterEach(() => { vi.useRealTimers() })

describe('上线通报', () => {
  it('先建立游标再登记上线，重复响应和重复事件只播放一次', async () => {
    const event = arrival(11)
    events.mockResolvedValueOnce({ cursor: 10, arrivals: [] }).mockResolvedValue({ cursor: 11, arrivals: [event, event] })
    const wrapper = mount(ForumBroadcast)
    await flushPromises()
    expect(events.mock.calls[0]?.[0]).toBeUndefined()
    expect(events.mock.calls[1]?.[0]).toBe(10)
    expect(events.mock.invocationCallOrder[0]).toBeLessThan(arrive.mock.invocationCallOrder[0]!)
    expect(arrive.mock.invocationCallOrder[0]).toBeLessThan(events.mock.invocationCallOrder[1]!)
    expect(wrapper.text()).toBe('星河')
    await wrapper.get('button').trigger('click')
    expect(wrapper.find('[data-broadcast]').exists()).toBe(false)
    await vi.advanceTimersByTimeAsync(10000); await flushPromises()
    expect(wrapper.find('[data-broadcast]').exists()).toBe(false)
    expect(arrive).toHaveBeenCalledOnce()
    wrapper.unmount()
    const calls = events.mock.calls.length
    await vi.advanceTimersByTimeAsync(10000)
    expect(events).toHaveBeenCalledTimes(calls)
  })
  it('忽略历史及过期事件，刷新重新建立游标，新的上线才播放', async () => {
    events.mockResolvedValueOnce({ cursor: 10, arrivals: [arrival(9)] }).mockResolvedValue({ cursor: 11, arrivals: [arrival(11, 60000)] })
    let wrapper = mount(ForumBroadcast); await flushPromises()
    expect(wrapper.find('[data-broadcast]').exists()).toBe(false)
    wrapper.unmount()
    events.mockResolvedValue({ cursor: 11, arrivals: [] })
    wrapper = mount(ForumBroadcast); await flushPromises()
    expect(wrapper.find('[data-broadcast]').exists()).toBe(false)
    events.mockResolvedValue({ cursor: 12, arrivals: [arrival(12)] })
    await vi.advanceTimersByTimeAsync(5000); await flushPromises()
    expect(wrapper.text()).toBe('星河')
    wrapper.unmount()
  })
  it('上线登记失败可重试，发言消息不会成为通报', async () => {
    arrive.mockRejectedValueOnce(new Error('network'))
    const wrapper = mount(ForumBroadcast); await flushPromises()
    expect(events).toHaveBeenCalledOnce()
    events.mockResolvedValue({ cursor: 10, arrivals: [], messages: [{ id: 999, rank: 1, content: '连续发言' }] })
    await vi.advanceTimersByTimeAsync(5000); await flushPromises()
    expect(arrive).toHaveBeenCalledTimes(2)
    expect(wrapper.find('[data-broadcast]').exists()).toBe(false)
    wrapper.unmount()
  })
  it('后台标签页不播放延迟响应，恢复后也不重播该事件', async () => {
    let resolve!: (value: unknown) => void
    events.mockResolvedValueOnce({ cursor: 10, arrivals: [] }).mockImplementationOnce(() => new Promise(r => { resolve = r }))
    const wrapper = mount(ForumBroadcast); await flushPromises()
    Object.defineProperty(document, 'hidden', { configurable: true, value: true })
    document.dispatchEvent(new Event('visibilitychange'))
    resolve({ cursor: 11, arrivals: [arrival(11)] }); await flushPromises()
    expect(wrapper.find('[data-broadcast]').exists()).toBe(false)
    await vi.advanceTimersByTimeAsync(10000)
    expect(events).toHaveBeenCalledTimes(2)
    Object.defineProperty(document, 'hidden', { configurable: true, value: false })
    events.mockResolvedValue({ cursor: 11, arrivals: [arrival(11)] })
    await vi.advanceTimersByTimeAsync(5000); await flushPromises()
    expect(wrapper.find('[data-broadcast]').exists()).toBe(false)
    wrapper.unmount()
  })
})
